import express from 'express';
import cookieParser from 'cookie-parser';
import { resolve } from 'node:path';
import { config } from './config.js';
import { pool } from './db/index.js';
import { sessions, csrfToken } from './auth/session.js';
import { oauthRouter } from './oauth/routes.js';
import { mcpRouter } from './mcp/routes.js';
import { webRouter } from './web/routes.js';
export const app = express();
app.disable('x-powered-by');
app.set('trust proxy', 1);
app.set('view engine', 'ejs');
app.set('views', resolve('src/web/views'));
app.use((req,res,next) => {
 res.set({ 'X-Content-Type-Options':'nosniff','Referrer-Policy':'no-referrer','X-Frame-Options':'DENY', 'Content-Security-Policy':"default-src 'self'; script-src 'self'; style-src 'self'; img-src 'self' data:; font-src 'self'; connect-src 'self'; frame-ancestors 'none'; base-uri 'none'; form-action 'self'", 'Permissions-Policy':'camera=(), microphone=(), geolocation=()' });
 if (config.production) res.set('Strict-Transport-Security','max-age=31536000');
 const start=Date.now();
 res.on('finish', () => { console.log(JSON.stringify({time:new Date().toISOString(),method:req.method,path:typeof req.route?.path==='string'?req.route.path:(req.path.startsWith('/.well-known/')?'discovery':'unmatched'),status:res.statusCode,duration_ms:Date.now()-start,...(req.path==='/token'?{grant_type:['authorization_code','refresh_token'].includes(req.body?.grant_type)?req.body.grant_type:'other'}:{})})); });
 next();
});
app.use('/.well-known',(req,res,next)=>{res.set({'Access-Control-Allow-Origin':'*','Access-Control-Allow-Methods':'GET, OPTIONS','Access-Control-Allow-Headers':'Authorization, Content-Type, Mcp-Session-Id, Mcp-Protocol-Version','Access-Control-Expose-Headers':'Authorization, Content-Type, Mcp-Session-Id, Mcp-Protocol-Version, WWW-Authenticate'});if(req.method==='OPTIONS'){res.sendStatus(204);return;}next();});
app.use(express.urlencoded({extended:false, limit:'256kb'}));
app.use(express.json({limit:'512kb'}));
app.use(cookieParser());
app.use('/public', express.static(resolve('src/web/public'), {maxAge:3600000,etag:true}));
app.get('/health', async (_req,res) => { try { await pool.query('SELECT 1');res.json({ok:true,db:'ok',version:config.version,uptime:Math.floor(process.uptime())}); } catch {res.status(503).json({ok:false,db:'unavailable',version:config.version,uptime:Math.floor(process.uptime())});}});
app.use(sessions);
app.use((req,res,next) => { res.locals.config=config; res.locals.user=req.user; res.locals.csrfToken=csrfToken(req); res.locals.csrf=res.locals.csrfToken; next(); });
app.use(oauthRouter);
app.use(mcpRouter);
app.use(webRouter);
app.use((_req,res) => res.status(404).type('text').send('Page not found'));
app.use((err:unknown,_req:express.Request,res:express.Response,_next:express.NextFunction) => { const status=typeof err==='object'&&err!==null&&'status' in err?Number(err.status):500;console.error(JSON.stringify({time:new Date().toISOString(),event:'request_error',code:status>=400&&status<500?'bad_request':'internal_error'}));if(!res.headersSent)res.status(status>=400&&status<500?status:500).json({error:status>=400&&status<500?'invalid_request':'server_error'});});
